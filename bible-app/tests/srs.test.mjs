import * as S from "../public/js/data/srs.js";
let fails = 0; const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const DAY = 86400000; let t = Date.parse("2026-11-17T15:00:00Z");
let s = S.fresh();
s = S.answer(s, "got", t); ok(s.interval === 1 && s.state === "review" && !s.inReview, `first Got it -> 1 day (${s.interval})`);
s = S.answer(s, "got", t += DAY); ok(s.interval === 3, `second Got it -> 3 days (${s.interval})`);
s = S.answer(s, "got", t += 3 * DAY); ok(s.interval >= 7, `third Got it -> grows by ease (${s.interval})`);
const rec = { id: "x", srs: s };
ok(S.categories(rec, t).has("strong"), "three Got it in a row with interval >= 7 -> Strong");
const before = s.interval;
s = S.answer(s, "almost", t += s.interval * DAY); ok(s.interval < before && s.ease < 2.65, `Almost -> sooner (${before} -> ${s.interval}), easier factor drops (${s.ease.toFixed(2)})`);
ok(S.categories({ srs: s }, t).has("weak"), "Almost -> Weak");
s = S.answer(s, "forgot", t += DAY); ok(s.interval === 0 && s.inReview && s.lapses === 1, "Forgot -> again this session, on Review list");
ok(Date.parse(s.due) - t < 1.5 * DAY, "Forgot -> due by tomorrow");
ok(S.categories({ srs: s }, t).has("review"), "Forgot -> in Review category");
s = S.answer(s, "got", t += 60000); ok(s.inReview, "one Got it is not enough to leave Review");
s = S.answer(s, "got", t += DAY); ok(!s.inReview, "two Got it in a row -> leaves Review");
ok(s.history.length === 7 && s.history.every(h => h.at && h.result), "every answer kept in history with its date");
ok(S.categories({}, t).has("notStudied") && S.categories({}, t).has("all"), "unanswered word -> Not studied");
// session building
const mk = (id, srs, addedAt) => ({ id, srs, addedAt });
const recs = [];
for (let i = 0; i < 30; i++) recs.push(mk("new" + i, undefined, "2026-11-0" + (1 + (i % 9))));
recs.push(mk("due1", { ...S.fresh(), reps: 2, due: "2026-11-16T10:00:00Z", interval: 3, lapses: 0 }));
recs.push(mk("struggle", { ...S.fresh(), reps: 5, due: "2026-11-17T10:00:00Z", interval: 1, lapses: 3, inReview: true }));
recs.push(mk("later", { ...S.fresh(), reps: 3, due: "2026-12-30T10:00:00Z", interval: 30 }));
const sess = S.buildSession(recs, { now: Date.parse("2026-11-17T16:00:00Z") });
ok(sess.cards.length === 12 && sess.cards[0] === "struggle" && sess.cards[1] === "due1", `session: struggling word first, then due, then 10 new (${sess.cards.slice(0, 3)} … ${sess.cards.length})`);
ok(!sess.cards.includes("later") && sess.newIds.length === 10, "not-yet-due words are skipped; new words limited to 10");
process.exit(fails ? 1 : 0);
